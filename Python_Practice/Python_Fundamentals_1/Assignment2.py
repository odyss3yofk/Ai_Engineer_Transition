# take two numbers as input and find the sum, difference, product and quotient of the two numbers.
num1 = int(input("enter first number"))
num2 = int(input("enter second number"))

sum = num1+num2
diff = num2-num1
product = num1*num2
quote = num2 / num1

print("the sum, difference, product and quotient are",
      sum, " ", diff, " ", product, " ", quote, " .")
